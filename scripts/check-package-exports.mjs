// Packaging guard: every declared export must be resolvable AND actually published.
//
// Why this exists: `src/browser/providers.d.mts` declared types for the deep specifier
// `@odatano/nightgate/browser/providers.mjs` while (a) that subpath was missing from
// `package.json#exports`, so Node and every bundler reject it with ERR_PACKAGE_PATH_NOT_EXPORTED,
// and (b) the `files` list covered `*.d.ts` but not `*.d.mts`, so the declaration would not have
// been in the tarball at all. Both are invisible in the repo - everything resolves fine from
// source - and only surface in a consumer's install. So the check runs against the REAL tarball
// contents (`npm pack --dry-run`), not against the working tree.
//
// Checks, per exports target (including every `types` condition):
//   1. the file exists on disk,
//   2. the file is included in the published tarball.
//
// Run: npm run check:exports
import { readFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
let failed = false;

/** Collect every file path referenced by the exports map, with the subpath that referenced it. */
function collectTargets(node, subpath, out) {
    if (typeof node === 'string') {
        out.push({ subpath, target: node });
        return;
    }
    if (node && typeof node === 'object') {
        for (const [key, value] of Object.entries(node)) {
            // Nested subpaths start with '.', condition keys ('types', 'import', 'default') do not.
            collectTargets(value, key.startsWith('.') && key !== '.' ? `${subpath}${key.slice(1)}` : subpath, out);
        }
    }
}

const targets = [];
collectTargets(pkg.exports ?? {}, '.', targets);

// `npm pack --dry-run --json` reports exactly what would ship, `files` globs already applied.
let packed;
try {
    const out = execFileSync('npm', ['pack', '--dry-run', '--json'], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
        shell: process.platform === 'win32',
    });
    packed = new Set(JSON.parse(out)[0].files.map((f) => f.path.replace(/\\/g, '/')));
} catch (e) {
    console.error(`check-package-exports: could not run "npm pack --dry-run": ${e.message}`);
    process.exit(1);
}

for (const { subpath, target } of targets) {
    const rel = target.replace(/^\.\//, '');
    if (!existsSync(rel)) {
        console.error(`check-package-exports: exports["${subpath}"] -> ${target} does not exist on disk.`);
        failed = true;
        continue;
    }
    if (!packed.has(rel)) {
        console.error(
            `check-package-exports: exports["${subpath}"] -> ${target} exists but is NOT published ` +
                `(no "files" entry matches it). Consumers would get ERR_MODULE_NOT_FOUND or untyped imports.`,
        );
        failed = true;
    }
}

// Every hand-written asset must be IN THE REPOSITORY, not just on this disk.
// Build output (a .ts source sits next to it) is regenerated by `npm run
// build` and is deliberately untracked; everything else has to be committed,
// or a fresh checkout (CI, a release build, another machine) silently lacks
// it. This is exactly how `src/browser/index.d.ts` could go missing after a
// `npm run clean` without any local check noticing.
let tracked;
try {
    tracked = new Set(
        execFileSync('git', ['ls-files'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
            .split('\n').map((l) => l.trim()).filter(Boolean)
    );
} catch {
    console.warn('check-package-exports: not a git checkout, skipping the tracked-asset check');
}
if (tracked) {
    const untracked = [];
    for (const rel of packed) {
        if (tracked.has(rel)) continue;
        // tsc output: the .ts source sits next to it.
        const fromTs = rel.replace(/\.(js|d\.ts|js\.map|d\.ts\.map)$/, '.ts');
        if (fromTs !== rel && existsSync(fromTs)) continue;
        // Generator output that is not committed by design.
        if (rel.startsWith('@cds-models/')) continue;                 // cds-typer
        if (/^contracts\/.*\/managed\//.test(rel)) continue;          // compactc
        untracked.push(rel);
    }
    if (untracked.length > 0) {
        console.error(
            'check-package-exports: these files are PACKED but neither tracked by git nor build output, ' +
                'so a fresh checkout (CI, release build, another machine) would ship without them:',
        );
        for (const rel of untracked.slice(0, 20)) console.error(`  - ${rel}`);
        if (untracked.length > 20) console.error(`  … and ${untracked.length - 20} more`);
        failed = true;
    }
}

// Non-export tarball invariants: files the runtime or the docs point users at.
//   - the migration CLI the SchemaNotDeployedError message recommends,
//   - the Compact source of the shipped managed artifacts (auditability: a
//     consumer must be able to diff source against the compiled circuits).
for (const required of [
    'scripts/apply-schema-delta.mjs',
    'contracts/attestation-vault/src/attestation-vault.compact',
    'contracts/attestation-vault-32/src/attestation-vault-32.compact',
    'contracts/attestation-vault-32/src/managed/attestation-vault-32/keys/proveDocumentComparison.prover'
]) {
    if (!packed.has(required)) {
        console.error(`check-package-exports: '${required}' is NOT in the tarball (files allowlist).`);
        failed = true;
    }
}

// Only the four shipped contracts may pack. Anything else under a
// contracts/<dir>/ (a local experiment, a stray artifact) would silently
// add prover keys to every install: the 8/64-slot width prototypes alone
// were ~240 MB. Files directly under contracts/ (README.md) are npm's own
// business, not a contract tree.
const SHIPPED_CONTRACTS = ['counter', 'attestation-vault', 'attestation-vault-32', 'shielded-token'];
for (const packedFile of packed) {
    const segments = packedFile.split('/');
    if (segments[0] !== 'contracts' || segments.length < 3) continue;
    if (!SHIPPED_CONTRACTS.includes(segments[1])) {
        console.error(`check-package-exports: unexpected contract file '${packedFile}' in the tarball.`);
        failed = true;
        break;
    }
}

if (failed) process.exit(1);
console.log(`check-package-exports: ok (${targets.length} export targets, all present and published)`);
